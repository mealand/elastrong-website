/**
 * Elastrong Cares Foundation — static site builder
 *
 *   node build.mjs           → builds HTML pages into public_html/
 *   node build.mjs --serve   → builds, then serves public_html/ on http://localhost:8080
 *
 * Pages live in src/pages/*.html. The first line of each page is a meta comment:
 *   <!--meta {"title":"About","description":"…","nav":"about"} -->
 * Placeholders:  {{site.email}}  {{page.title}}  {{year}}  and partials {{> header}}
 * All organisation details live in site.config.json — edit there, rebuild, upload.
 */
import fs from 'node:fs';
import path from 'node:path';
import http from 'node:http';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(ROOT, 'src');
const OUT = path.join(ROOT, 'public_html');
const site = JSON.parse(fs.readFileSync(path.join(ROOT, 'site.config.json'), 'utf8'));
const build = Date.now().toString(36);

const partials = Object.fromEntries(
  fs.readdirSync(path.join(SRC, 'partials'))
    .filter(f => f.endsWith('.html'))
    .map(f => [f.replace('.html', ''), fs.readFileSync(path.join(SRC, 'partials', f), 'utf8')])
);

const lookup = (obj, key) => key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);

function render(tpl, ctx, depth = 0) {
  if (depth > 5) return tpl;
  tpl = tpl.replace(/\{\{>\s*([\w-]+)\s*\}\}/g, (_, name) => {
    if (!(name in partials)) throw new Error(`Unknown partial: ${name}`);
    return render(partials[name], ctx, depth + 1);
  });
  return tpl.replace(/\{\{\s*([\w.]+)\s*\}\}/g, (m, key) => {
    const v = lookup(ctx, key);
    return v == null ? m : String(v);
  });
}

const pages = fs.readdirSync(path.join(SRC, 'pages')).filter(f => f.endsWith('.html'));
const sitemap = [];

for (const file of pages) {
  const raw = fs.readFileSync(path.join(SRC, 'pages', file), 'utf8');
  const m = raw.match(/^<!--meta\s+([\s\S]*?)-->\s*/);
  if (!m) throw new Error(`${file}: missing <!--meta {...} --> header`);
  const meta = JSON.parse(m[1]);
  const body = raw.slice(m[0].length);
  const slug = file.replace('.html', '');
  const page = {
    file,
    slug,
    url: slug === 'index' ? `${site.domain}/` : `${site.domain}/${file}`,
    fullTitle: meta.fullTitle || `${meta.title} | ${site.name}`,
    bodyClass: meta.bodyClass || `page-${slug}`,
    ogImage: meta.ogImage || 'assets/images/og-image.jpg',
    baseTag: meta.base ? '<base href="/">' : '',
    robots: site.indexable && !meta.noindex ? 'index, follow' : 'noindex, nofollow',
    ...meta,
  };
  const ctx = { site, page, year: new Date().getFullYear(), build };

  let html = render(
    `<!doctype html>
<html lang="en-NG">
<head>
{{> head}}
</head>
<body class="{{page.bodyClass}}">
{{> icons}}
{{> header}}
<main id="main">
${body}
</main>
${meta.hideCta ? '' : '{{> footer-cta}}'}
{{> footer}}
</body>
</html>
`, ctx);

  if (meta.nav) {
    html = html.replaceAll(`data-nav="${meta.nav}"`, `data-nav="${meta.nav}" aria-current="page"`);
  }
  fs.writeFileSync(path.join(OUT, file), html);
  if (!meta.noindex) sitemap.push({ url: page.url, priority: slug === 'index' ? '1.0' : '0.8' });
  console.log(`  ✓ ${file}`);
}

// Runtime config for the browser (donation settings etc.)
const clientCfg = {
  name: site.name,
  email: site.email,
  whatsapp: site.whatsapp,
  donate: site.donate,
};
fs.writeFileSync(
  path.join(OUT, 'assets/js/config.js'),
  `/* Generated by build.mjs from site.config.json — do not edit by hand. */\nwindow.ECF_CONFIG = ${JSON.stringify(clientCfg, null, 2)};\n`
);

// sitemap.xml
const today = new Date().toISOString().slice(0, 10);
fs.writeFileSync(
  path.join(OUT, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${sitemap.map(s => `  <url><loc>${s.url}</loc><lastmod>${today}</lastmod><priority>${s.priority}</priority></url>`).join('\n')}
</urlset>
`
);

// robots.txt: blocks search engines until site.config.json "indexable" is true
fs.writeFileSync(
  path.join(OUT, 'robots.txt'),
  site.indexable
    ? `User-agent: *\nAllow: /\nDisallow: /forms/\n\nSitemap: ${site.domain}/sitemap.xml\n`
    : 'User-agent: *\nDisallow: /\n'
);
if (!site.indexable) console.log('  ⚠ indexable=false: search engines are blocked (set "indexable": true at launch)');

// Media checklist: every image/video slot referenced by the pages, and whether the file exists yet
const slots = new Map();
for (const file of pages) {
  const html = fs.readFileSync(path.join(OUT, file), 'utf8');
  for (const [, p] of html.matchAll(/(?:src|poster|href|data-video)="(assets\/(?:images|videos)\/[^"]+)"/g)) {
    if (!slots.has(p)) slots.set(p, new Set());
    slots.get(p).add(file);
  }
}
const rows = [...slots.entries()].sort(([a], [b]) => a.localeCompare(b));
const have = rows.filter(([p]) => fs.existsSync(path.join(OUT, p))).length;
fs.writeFileSync(
  path.join(ROOT, 'MEDIA-CHECKLIST.md'),
  `# Media checklist\n\nGenerated by \`node build.mjs\`. Drop a file at the exact path below and it replaces the animated placeholder automatically.\n\n**${have} / ${rows.length}** slots filled.\n\n| Status | File (inside public_html/) | Used on |\n|---|---|---|\n` +
    rows.map(([p, used]) => `| ${fs.existsSync(path.join(OUT, p)) ? '✅' : '⬜'} | \`${p}\` | ${[...used].join(', ')} |`).join('\n') +
    '\n'
);
console.log(`\nBuilt ${pages.length} pages · media slots filled: ${have}/${rows.length} (see MEDIA-CHECKLIST.md)`);

// Tiny static server for local preview
if (process.argv.includes('--serve')) {
  const types = {
    '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json',
    '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp',
    '.mp4': 'video/mp4', '.webm': 'video/webm', '.xml': 'application/xml', '.ico': 'image/x-icon', '.webmanifest': 'application/manifest+json',
  };
  const port = Number(process.env.PORT) || 8080;
  http.createServer((req, res) => {
    let p = decodeURIComponent(new URL(req.url, 'http://x').pathname);
    if (p.endsWith('/')) p += 'index.html';
    let fp = path.join(OUT, p);
    if (!fp.startsWith(OUT)) { res.writeHead(403).end(); return; }
    if (!fs.existsSync(fp) && fs.existsSync(fp + '.html')) fp += '.html';
    if (!fs.existsSync(fp) || fs.statSync(fp).isDirectory()) {
      res.writeHead(404, { 'Content-Type': types['.html'] });
      fs.createReadStream(path.join(OUT, '404.html')).pipe(res);
      return;
    }
    const stat = fs.statSync(fp);
    const type = types[path.extname(fp).toLowerCase()] || 'application/octet-stream';
    const range = req.headers.range;
    if (range && type.startsWith('video')) {
      const [s, e] = range.replace('bytes=', '').split('-');
      const start = Number(s), end = e ? Number(e) : stat.size - 1;
      res.writeHead(206, { 'Content-Range': `bytes ${start}-${end}/${stat.size}`, 'Accept-Ranges': 'bytes', 'Content-Length': end - start + 1, 'Content-Type': type });
      fs.createReadStream(fp, { start, end }).pipe(res);
      return;
    }
    res.writeHead(200, { 'Content-Type': type, 'Content-Length': stat.size });
    fs.createReadStream(fp).pipe(res);
  }).listen(port, () => console.log(`\nPreview: http://localhost:${port}`));
}
